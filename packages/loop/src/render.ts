import { weekLabel } from './budget.js';
import type { ResolvedAgentConfig } from './config.js';
import type { GateResult } from './gates.js';
import type { Issue } from './issue.js';
import type { RunRecord } from './ledger.js';
import type { LoopResult } from './loop.js';
import { planNamesNoRisks, wrapPlan } from './plan.js';

const GENERATED = 'Generated by agentic-loop from gate runs and the model\'s usage report, not from the agent\'s own claims.';

function seconds(ms: number): string {
  return `${(ms / 1000).toFixed(1)} s`;
}

function n(v: number): string {
  return v.toLocaleString('en-US');
}

function usd(v: number | null): string {
  return v === null ? 'not priced' : `$${v.toFixed(2)}`;
}

function details(summary: string, body: string): string {
  const text = body.trim() ? body.replace(/```/g, "'''") : '(no output)';
  return `<details><summary>${summary}</summary>\n\n\`\`\`\n${text}\n\`\`\`\n\n</details>`;
}

function gateTable(gates: readonly GateResult[]): string {
  const rows = gates.map((g) => `| ${g.name} | \`${g.command}\` | ${g.status.toUpperCase()} | ${seconds(g.durationMs)} |`);
  return ['| Gate | Command | Result | Time |', '|---|---|---|---|', ...rows].join('\n');
}

function loopFacts(r: RunRecord): string {
  const attempts = r.phases.map((p) => `${p.phase} ${p.attempts.length}`).join(', ');
  const reverted = [...new Set(r.phases.flatMap((p) => p.attempts.flatMap((a) => [...a.protectedPathViolations, ...a.lockedTestEdits])))];
  return [
    `- Attempts: ${attempts}`,
    `- Caught by the loop before review: ${r.caughtBy.length > 0 ? r.caughtBy.join(', ') : 'nothing'}`,
    `- Protected or locked files reverted: ${reverted.length > 0 ? reverted.join(', ') : 'none'}`,
    `- Model requests: ${n(r.usage.requests ?? 0)}. Tokens: ${n(r.usage.input)} in (${n(r.usage.cachedInput)} cached), ${n(r.usage.output)} out. Cost: ${usd(r.costUsd)}`,
    `- Model: ${r.model} via ${r.runner}`,
  ].join('\n');
}

function reviewSection(result: LoopResult): string[] {
  const r = result.review;
  if (!r) return [];
  const head = `Advisory only: a separate ${r.model} session checked the work against the issue. It does not block the merge.`;
  if (r.findings === null) return ['## Independent review', head, 'The reviewer gave no usable answer, so this work was not independently reviewed.'];
  if (r.findings.length === 0) return ['## Independent review', head, 'No findings.'];
  const rows = r.findings.map((f) => `| ${f.kind} | ${f.severity} | ${f.file ?? ''} | ${f.summary.replace(/\|/g, '/')} |`);
  const fix =
    r.fixRound === 'kept'
      ? 'The agent had one fix round for the high and medium findings, and every gate still passes. The fix was not reviewed again: check it.'
      : r.fixRound === 'discarded'
        ? `The fix round was discarded. ${r.fixNote ?? ''}`.trim()
        : 'No fix round was run.';
  return ['## Independent review', head, ['| Kind | Severity | File | Finding |', '|---|---|---|---|', ...rows].join('\n'), fix];
}

export function renderPlanPrBody(issue: Issue, result: LoopResult, config: ResolvedAgentConfig): string {
  const tests = result.record.phases.find((p) => p.phase === 'red')?.passed ? result.lockedTests ?? [] : [];
  const parts = [
    `Plan for #${issue.number}. **Waiting for approval: nothing is implemented until a person approves this plan.**`,
    '## Plan',
    result.plan?.trim() ? wrapPlan(result.plan) : 'The agent gave no plan.',
  ];
  if (result.plan?.trim() && planNamesNoRisks(result.plan)) {
    parts.push('**Check before approving:** the plan names no risks. Every change can break something; ask for them in a comment and re-plan if it matters here.');
  }
  parts.push(
    '## Failing tests',
    tests.length > 0 ? tests.map((t) => `- \`${t}\``).join('\n') : 'See the files in this pull request.',
  );
  if (result.redRun) {
    parts.push(
      `\`${result.redRun.command}\` fails with exit code ${result.redRun.exitCode}, because the behaviour does not exist yet.`,
      details('Red output', result.redRun.outputTail),
    );
  }
  parts.push(
    '## How to decide',
    [
      `- **Approve:** add the \`${config.labels.planApproved}\` label to this pull request (or to #${issue.number}). The loop then implements it on this branch with these tests locked.`,
      `- **Reject:** comment on this pull request or request changes, saying what to change, then add \`${config.labels.ready}\` to #${issue.number}. The loop writes a new plan and new tests using your comments.`,
    ].join('\n'),
    '## Loop',
    loopFacts(result.record),
    `_${GENERATED}_`,
  );
  return `${parts.join('\n\n')}\n`;
}

export function renderPrBody(issue: Issue, result: LoopResult, config?: ResolvedAgentConfig): string {
  const parts = [`Closes #${issue.number}`];
  if (result.stage === 'build') parts.push('The plan and failing tests were approved before this implementation started.');
  parts.push('## Agent summary', result.summary.trim() || 'The agent gave no summary.');
  if (result.unplannedFiles && result.unplannedFiles.length > 0) {
    parts.push(
      '## Outside the approved plan',
      'The plan does not mention these files, but the build changed them. Check each one: an unplanned change may be needed, or may be scope the plan reviewer never saw.',
      result.unplannedFiles.map((f) => `- \`${f}\``).join('\n'),
    );
  }
  if (result.stage === 'build' && result.plan?.trim()) {
    parts.push(`<details><summary>Approved plan</summary>\n\n${wrapPlan(result.plan)}\n\n</details>`);
  }
  if (result.redRun) {
    parts.push(
      '## Red run (tests first)',
      `\`${result.redRun.command}\` failed as expected with exit code ${result.redRun.exitCode} before the implementation existed.`,
      details('Red output', result.redRun.outputTail),
    );
  }
  parts.push('## Green run', gateTable(result.finalGates));
  parts.push(...reviewSection(result));
  if (config && result.stage === 'build') {
    parts.push(
      '## Asking for changes',
      `Comment on this pull request with what to fix, then add \`${config.labels.planApproved}\` to it (or to #${issue.number}). The loop rebuilds on this branch with your comments; the approved plan and tests stay locked. To change the plan itself, add \`${config.labels.ready}\` to #${issue.number} instead.`,
    );
  }
  parts.push('## Loop', loopFacts(result.record));
  parts.push(`_${GENERATED}_`);
  return `${parts.join('\n\n')}\n`;
}

export function renderFailureComment(issue: Issue, result: LoopResult, config: ResolvedAgentConfig): string {
  const parts = [`The agent loop stopped on #${issue.number} and needs a human. ${result.stopReason ?? ''}`.trim()];
  const lastAttempt = result.record.phases.at(-1)?.attempts.at(-1);
  if (lastAttempt?.failure) parts.push(`Last failure: \`${lastAttempt.failure}\``);
  const failed = result.finalGates.find((g) => g.status === 'fail');
  if (failed) parts.push(details(`Output of gate "${failed.name}"`, failed.outputTail));
  parts.push('## Loop', loopFacts(result.record));
  parts.push(
    `Fix the issue description or the code, then add the \`${config.labels.ready}\` label again to retry. Any hand edit counts as a human intervention.`,
  );
  parts.push(`_${GENERATED}_`);
  return `${parts.join('\n\n')}\n`;
}

/** The weekly budget and loop metrics page, rendered from the ledger. */
export function renderBudgetReport(records: readonly RunRecord[], config: ResolvedAgentConfig, now: Date): string {
  const byWeek = new Map<string, RunRecord[]>();
  for (const r of records) {
    const wk = weekLabel(new Date(r.finishedAt), config.budget.utcOffset);
    byWeek.set(wk, [...(byWeek.get(wk) ?? []), r]);
  }
  const weeks = [...byWeek.keys()].sort();
  const weekRows = weeks.map((wk) => {
    const rs = byWeek.get(wk) ?? [];
    const passed = rs.filter((r) => r.outcome === 'passed').length;
    const plans = rs.filter((r) => r.outcome === 'plan-ready').length;
    const needsHuman = rs.filter((r) => r.outcome === 'needs-human').length;
    const first = rs.filter((r) => r.firstPass).length;
    const tokens = rs.reduce((s, r) => s + r.usage.total, 0);
    const priced = rs.every((r) => r.costUsd !== null);
    const cost = rs.reduce((s, r) => s + (r.costUsd ?? 0), 0);
    const cap = config.budget.weeklyUsd;
    return `| ${wk} | ${rs.length} | ${plans} | ${passed} | ${needsHuman} | ${first} | ${n(Math.round(tokens / Math.max(1, rs.length)))} | ${priced ? usd(cost) : `${usd(cost)} (some runs unpriced)`}${cap ? ` of $${cap}` : ''} |`;
  });

  const caught = new Map<string, number>();
  for (const r of records) for (const c of r.caughtBy) caught.set(c, (caught.get(c) ?? 0) + 1);
  const caughtRows = [...caught.entries()].sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`);

  // Tokens are not comparable across models, so models are compared by cost per run.
  const byModel = new Map<string, RunRecord[]>();
  for (const r of records) byModel.set(r.model, [...(byModel.get(r.model) ?? []), r]);
  const modelRows = [...byModel.entries()].sort().map(([model, rs]) => {
    const passed = rs.filter((r) => r.outcome === 'passed').length;
    const first = rs.filter((r) => r.firstPass).length;
    const priced = rs.filter((r) => r.costUsd !== null);
    const perRun = priced.length > 0 ? priced.reduce((s, r) => s + (r.costUsd ?? 0), 0) / priced.length : null;
    return `| ${model} | ${rs.length} | ${passed} | ${first} | ${usd(perRun)} |`;
  });

  const recent = [...records].sort((a, b) => b.finishedAt.localeCompare(a.finishedAt)).slice(0, 20);
  const runRows = recent.map(
    (r) =>
      `| ${r.finishedAt.slice(0, 16).replace('T', ' ')} | #${r.issue} | ${r.stage ?? 'full'} | ${r.model} | ${r.outcome} | ${r.phases.map((p) => `${p.phase} ${p.attempts.length}`).join(', ')} | ${n(r.usage.total)} | ${usd(r.costUsd)} |`,
  );
  const routing =
    config.routes.length > 0
      ? `Default model: ${config.model}. Routes: ${config.routes.map((r) => `${r.labels.join(' or ')} to ${r.model}`).join('; ')}.`
      : `Model: ${config.model}.`;

  return [
    '# Agent loop budget and metrics',
    `_${GENERATED} Do not edit by hand. Updated ${now.toISOString().slice(0, 16).replace('T', ' ')} UTC._`,
    `${routing} Weekly cap: ${config.budget.weeklyUsd ? `$${config.budget.weeklyUsd}, bug issues only from ${Math.round(config.budget.bugOnlyAt * 100)}%, stop at ${Math.round(config.budget.stopAt * 100)}%` : 'none'}.`,
    '## By week',
    '| Week of | Runs | Plans ready | Built | Needs human | First pass | Tokens per run | Cost |',
    '|---|---|---|---|---|---|---|---|',
    ...(weekRows.length > 0 ? weekRows : ['| none | 0 | 0 | 0 | 0 | 0 | 0 | $0.00 |']),
    '## What the loop caught before review',
    '| Check | Times |',
    '|---|---|',
    ...(caughtRows.length > 0 ? caughtRows : ['| none | 0 |']),
    '## By model',
    '| Model | Runs | Passed | First pass | Cost per run |',
    '|---|---|---|---|---|',
    ...(modelRows.length > 0 ? modelRows : ['| none | 0 | 0 | 0 | not priced |']),
    '## Latest runs',
    '| Finished (UTC) | Issue | Stage | Model | Outcome | Attempts | Tokens | Cost |',
    '|---|---|---|---|---|---|---|---|',
    ...(runRows.length > 0 ? runRows : ['| none | | | | | | | |']),
    '',
  ].join('\n');
}
